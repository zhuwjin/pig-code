#!/usr/bin/env python3
import argparse
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPECIAL_ICONS = {"pig"}
IGNORED_TAGS = {"svg", "g", "defs", "title", "desc", "metadata"}


def local_name(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def number(element: ET.Element, name: str, default: float | None = None) -> int | float:
    raw = element.get(name)
    if raw is None:
        if default is None:
            raise ValueError(f"missing {name}")
        return default
    value = float(raw)
    return int(value) if value.is_integer() else value


def convert_shape(element: ET.Element) -> dict:
    tag = local_name(element.tag)
    if tag == "path":
        result = {"tag": "path", "d": " ".join(element.get("d", "").split())}
    elif tag == "circle":
        result = {
            "tag": "circle",
            "cx": number(element, "cx"),
            "cy": number(element, "cy"),
            "r": number(element, "r"),
        }
    elif tag == "ellipse":
        result = {
            "tag": "ellipse",
            "cx": number(element, "cx"),
            "cy": number(element, "cy"),
            "rx": number(element, "rx"),
            "ry": number(element, "ry"),
        }
    elif tag == "rect":
        result = {
            "tag": "rect",
            "x": number(element, "x", 0),
            "y": number(element, "y", 0),
            "width": number(element, "width"),
            "height": number(element, "height"),
        }
        for name in ("rx", "ry"):
            if element.get(name) is not None:
                result[name] = number(element, name)
    elif tag == "line":
        result = {
            "tag": "line",
            "x1": number(element, "x1"),
            "y1": number(element, "y1"),
            "x2": number(element, "x2"),
            "y2": number(element, "y2"),
        }
    elif tag in {"polyline", "polygon"}:
        result = {"tag": tag, "points": " ".join(element.get("points", "").split())}
    else:
        raise ValueError(f"unsupported element <{tag}>")
    if element.get("fill") == "currentColor":
        result["filled"] = True
    return result


def convert_svg(path: Path) -> list[dict]:
    root = ET.parse(path).getroot()
    view_box = [float(value) for value in root.get("viewBox", "").replace(",", " ").split()]
    if view_box != [0, 0, 24, 24]:
        raise ValueError(f"unsupported viewBox: {root.get('viewBox')}")
    shapes = []
    for element in root.iter():
        tag = local_name(element.tag)
        if tag in IGNORED_TAGS:
            continue
        if element.get("transform") is not None:
            raise ValueError(f"unsupported transform on <{tag}>")
        fill = element.get("fill")
        if fill not in (None, "none", "currentColor"):
            raise ValueError(f"unsupported fill {fill!r} on <{tag}>")
        stroke = element.get("stroke")
        if stroke not in (None, "currentColor"):
            raise ValueError(f"unsupported stroke {stroke!r} on <{tag}>")
        if element.get("style") is not None:
            raise ValueError(f"unsupported inline style on <{tag}>")
        shapes.append(convert_shape(element))
    if not shapes:
        raise ValueError("no drawable elements")
    for shape in shapes:
        if shape["tag"] == "path" and not shape["d"]:
            raise ValueError("empty path")
        if shape["tag"] in {"polyline", "polygon"} and not shape["points"]:
            raise ValueError(f"empty {shape['tag']}")
    return shapes


def generate(input_dir: Path) -> str:
    icons = {}
    errors = []
    paths = sorted(input_dir.glob("*.svg"), key=lambda path: path.stem)
    if not paths:
        raise ValueError(f"no SVG files found in {input_dir}")
    for path in paths:
        name = path.stem
        if name in SPECIAL_ICONS:
            continue
        try:
            icons[name] = convert_svg(path)
        except (ET.ParseError, ValueError) as error:
            errors.append(f"{path.name}: {error}")
    if errors:
        details = "\n".join(errors[:40])
        remaining = len(errors) - min(len(errors), 40)
        suffix = f"\n... and {remaining} more" if remaining > 0 else ""
        raise ValueError(f"{len(errors)} SVG files could not be converted:\n{details}{suffix}")
    payload = json.dumps(icons, ensure_ascii=False, indent=2)
    return (
        "// Generated by scripts/generate_icons.py; do not edit manually.\n"
        'import type { IconElement } from "./icon-types";\n\n'
        f"export const ICON_ELEMENTS = {payload} satisfies Record<string, readonly IconElement[]>;\n"
    )


def write_if_changed(output: Path, content: str) -> bool:
    if output.exists() and output.read_text(encoding="utf-8") == content:
        return False
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="\n") as file:
        file.write(content)
    temporary.replace(output)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Canvas icon geometry from SVG files.")
    parser.add_argument("--input", type=Path, default=ROOT / "apps" / "desktop" / "assets" / "icons")
    parser.add_argument("--output", type=Path, default=ROOT / "apps" / "desktop" / "app" / "components" / "icon-elements.ts")
    parser.add_argument("--check", action="store_true", help="fail when the generated file is not current")
    args = parser.parse_args()
    try:
        content = generate(args.input)
    except ValueError as error:
        print(error, file=sys.stderr)
        return 1
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
            print(f"Out of date: {args.output}. Run python scripts/generate_icons.py", file=sys.stderr)
            return 1
        print(f"Icon geometry is current: {args.output}")
        return 0
    changed = write_if_changed(args.output, content)
    count = content.count('": [')
    print(f"{'Generated' if changed else 'Already current'}: {args.output} ({count} icons)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
